/// Entity hướng dẫn an toàn dã ngoại thực địa
class SafetyGuideline {
  final String waterAdvice;
  final String mobileCoverageSummary;
  final List<String> primaryHazards;
  final List<String> requiredGear;
  final String emergencyContactInfo;
  final String verificationDate;
  final String verifiedBy;

  const SafetyGuideline({
    required this.waterAdvice,
    required this.mobileCoverageSummary,
    required this.primaryHazards,
    required this.requiredGear,
    required this.emergencyContactInfo,
    required this.verificationDate,
    required this.verifiedBy,
  });
}

